//! Decodes Gource's sprite PNGs (`data/*.png`) into raw RGBA8 at build time,
//! so the wasm module embeds pixels and needs no image decoder at run time.
//! Writes `<name>.rgba` and `textures.rs` (dimensions + `include_bytes!`) into
//! `OUT_DIR`. Native builds skip the work: the crate is empty there.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

const TEXTURES: [(&str, &str); 4] = [
    ("FILE", "file"),
    ("USER", "user"),
    ("BEAM", "beam"),
    ("DECO", "decorations"),
];

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let data = manifest.join("../../data");
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());

    for (_, name) in TEXTURES {
        println!(
            "cargo::rerun-if-changed={}",
            data.join(format!("{name}.png")).display()
        );
    }

    if env::var("CARGO_CFG_TARGET_ARCH").as_deref() != Ok("wasm32") {
        return;
    }

    let mut rs = String::from("// Generated by build.rs from data/*.png.\n");
    for (konst, name) in TEXTURES {
        let (w, h, rgba) = decode(&data.join(format!("{name}.png")));
        let file = out.join(format!("{name}.rgba"));
        fs::write(&file, rgba).unwrap();
        writeln!(
            rs,
            "pub const {konst}: RgbaImage = RgbaImage {{ width: {w}, height: {h}, pixels: \
             include_bytes!(concat!(env!(\"OUT_DIR\"), \"/{name}.rgba\")) }};"
        )
        .unwrap();
    }
    fs::write(out.join("textures.rs"), rs).unwrap();
}

/// Decode to 8-bit straight-alpha RGBA, as SDL_image hands Gource the pixels.
fn decode(path: &Path) -> (u32, u32, Vec<u8>) {
    let file = fs::File::open(path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    let mut decoder = png::Decoder::new(std::io::BufReader::new(file));
    decoder.set_transformations(png::Transformations::normalize_to_color8());
    let mut reader = decoder.read_info().unwrap();
    let mut buf = vec![0; reader.output_buffer_size().unwrap()];
    let info = reader.next_frame(&mut buf).unwrap();
    let px = (info.width * info.height) as usize;
    let src = &buf[..info.buffer_size()];
    let rgba = match info.color_type {
        png::ColorType::Rgba => src.to_vec(),
        png::ColorType::Rgb => src
            .as_chunks::<3>()
            .0
            .iter()
            .flat_map(|&[r, g, b]| [r, g, b, 255])
            .collect(),
        png::ColorType::GrayscaleAlpha => src
            .as_chunks::<2>()
            .0
            .iter()
            .flat_map(|&[g, a]| [g, g, g, a])
            .collect(),
        png::ColorType::Grayscale => src.iter().flat_map(|&g| [g, g, g, 255]).collect(),
        png::ColorType::Indexed => unreachable!("normalize_to_color8 expands palettes"),
    };
    assert_eq!(rgba.len(), px * 4, "{}", path.display());
    (info.width, info.height, rgba)
}
